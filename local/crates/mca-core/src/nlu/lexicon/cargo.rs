/// Special-requirement cues the customer mentions, kept verbatim (trimmed) so
/// a manager sees the customer's own words.
pub fn special_requirement(text: &str) -> Option<String> {
    const MARKERS: &[&str] = &[
        "хрупк",
        "не кантовать",
        "сухой",
        "без переворота",
        "вертикально",
        "температур",
        "мороз",
        "опасно",
        "взрыв",
        "аккуратно",
        "срочн",
        "негабаритн",
        "гидравлик",
        "погрузчик",
        "кран",
        "разгрузк",
        "застрах",
        "air ride",
        "истира",
    ];
    MARKERS
        .iter()
        .find(|m| text.contains(**m))
        .map(|m| (*m).to_string())
}

