/// Cargo-type lexicon: surface forms → canonical Russian cargo description.
/// Order matters: the first match wins, so more specific phrases come first.
pub fn canonical_cargo(text: &str) -> Option<String> {
    CARGO
        .iter()
        .find(|(_, aliases)| aliases.iter().any(|a| text.contains(a)))
        .map(|(canonical, _)| (*canonical).to_string())
}

